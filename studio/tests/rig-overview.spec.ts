import { expect, test } from '@playwright/test'
import { noGPU, saved } from './helpers'

test('shaded overview follows rig and scan changes while orbiting leaves the physical camera untouched', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await noGPU(page); await page.goto('/')
  const stage = page.locator('.rig-overview-stage')
  await expect(stage).toHaveAttribute('data-ready', 'true')
  await stage.scrollIntoViewIfNeeded()
  await expect(page.locator('.rig-overview-error')).toHaveCount(0)
  const initial = await stage.screenshot()
  await page.getByRole('button', { name: 'Left light position', exact: true }).focus()
  await page.keyboard.press('Shift+ArrowUp')
  await expect.poll(async () => (await saved(page)).lights[0].height).toBe(390)
  await expect.poll(async () => (await stage.screenshot()).equals(initial)).toBe(false)
  const adjusted = await stage.screenshot()
  await page.getByRole('button', { name: 'Lock rig / Preview scan' }).click()
  const fixed = await saved(page)
  await page.getByLabel('Viewed position from base', { exact: true }).fill('100')
  await expect.poll(async () => (await saved(page)).blade.x).toBe(250)
  await expect.poll(async () => (await stage.screenshot()).equals(adjusted)).toBe(false)
  expect((await saved(page)).camera).toEqual(fixed.camera)
  expect((await saved(page)).lights).toEqual(fixed.lights)
  const beforeOrbit = await saved(page), image = await stage.screenshot(), box = (await stage.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 70, box.y + box.height / 2 + 35, { steps: 5 })
  await page.mouse.up()
  await expect.poll(async () => (await stage.screenshot()).equals(image)).toBe(false)
  expect(await saved(page)).toEqual(beforeOrbit)
  await page.getByRole('button', { name: 'Reset 3D view' }).click()
  expect(await saved(page)).toEqual(beforeOrbit)
  await page.setViewportSize({ width: 390, height: 844 })
  await stage.scrollIntoViewIfNeeded()
  expect((await stage.boundingBox())!.width).toBeLessThan(390)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
